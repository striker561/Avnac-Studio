#!/usr/bin/env node
/**
 * Stamp the release version into every place the build reads it from.
 *
 * The release workflow runs this with the pushed tag before `wails build`, so
 * a `v1.4.0` tag produces a 1.4.0 binary, dmg, installer and window title
 * without a hand-edit commit.
 *
 * Usage:
 *   node scripts/set-version.mjs                 # version from the git tag / GITHUB_REF_NAME
 *   node scripts/set-version.mjs v1.4.0          # explicit version
 *   node scripts/set-version.mjs v1.4.0 --check   # exit 1 if anything is out of date
 *   node scripts/set-version.mjs v1.4.0 --root .  # operate on another checkout
 *
 * Every literal is matched with a narrow, anchored pattern and a missing match
 * is a hard error: a refactor that renames one of these must not silently ship
 * a binary reporting the wrong version.
 */
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "..");

const SEMVER_PATTERN = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;

/** Where the version lives, and how to rewrite it in place. */
const TARGETS = [
  {
    file: "main.go",
    description: "version reported by the app (matches the GitHub release tag)",
    pattern: /(var appVersion = ")([^"]*)(")/,
    // The updater compares this against release tag names, which start with v.
    render: (semver) => `v${semver}`,
  },
  {
    file: "wails.json",
    description: "drives the exe metadata, dmg and NSIS installer",
    pattern: /("productVersion"\s*:\s*")([^"]*)(")/,
    render: (semver) => semver,
  },
  {
    file: "build/windows/installer/wails_tools.nsh",
    description: "installer defines (regenerated by `wails build -nsis`)",
    pattern: /(!define INFO_PRODUCTVERSION ")([^"]*)(")/,
    render: (semver) => semver,
    optional: true,
  },
];

/**
 * Files that read the version through Wails' template variables rather than a
 * literal. Listed so a future hard-coded number in one of them is noticed.
 */
const TEMPLATED = [
  "build/windows/info.json",
  "build/darwin/Info.plist",
  "build/darwin/Info.dev.plist",
];

function fail(message) {
  console.error(`set-version: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  const options = { version: null, root: REPO_ROOT, check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") {
      options.check = true;
    } else if (arg === "--root") {
      const value = argv[i + 1];
      if (!value) fail("--root needs a directory");
      options.root = path.resolve(value);
      i += 1;
    } else if (arg.startsWith("--root=")) {
      options.root = path.resolve(arg.slice("--root=".length));
    } else if (arg.startsWith("-")) {
      fail(`unknown option ${arg}`);
    } else if (!options.version) {
      options.version = arg;
    } else {
      fail(`unexpected argument ${arg}`);
    }
  }
  return options;
}

function versionFromEnvironment() {
  const fromCi = process.env.GITHUB_REF_NAME?.trim();
  if (fromCi) return fromCi;
  try {
    return execFileSync("git", ["describe", "--tags", "--exact-match"], {
      cwd: REPO_ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

function normalize(raw) {
  if (!raw) {
    fail(
      "no version given. Pass one (v1.2.3), or run on a tag so GITHUB_REF_NAME is set.",
    );
  }
  const semver = raw.trim().replace(/^v/i, "");
  if (!SEMVER_PATTERN.test(semver)) {
    fail(`"${raw}" is not a version. Expected v1.2.3 or 1.2.3 (pre-release suffix allowed).`);
  }
  return semver;
}

async function readIfExists(file) {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function warnAboutTemplates(root) {
  for (const relative of TEMPLATED) {
    const text = await readIfExists(path.join(root, relative));
    if (text === null) continue;
    if (!text.includes("{{.Info.ProductVersion}}")) {
      console.warn(
        `set-version: warning: ${relative} no longer uses {{.Info.ProductVersion}}; check where its version comes from.`,
      );
    }
  }
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const version = normalize(options.version ?? versionFromEnvironment());
  const tag = `v${version}`;

  console.log(`set-version: target ${tag}`);

  if (version.includes("-")) {
    console.warn(
      "set-version: warning: pre-release suffix. The Windows exe and installer expect numeric versions; the release workflow only builds stable vX.Y.Z tags.",
    );
  }

  const stale = [];
  for (const target of TARGETS) {
    const file = path.join(options.root, target.file);
    const text = await readIfExists(file);

    if (text === null) {
      if (target.optional) {
        console.log(`  ${target.file}: not present, skipped`);
        continue;
      }
      fail(`${target.file} is missing (${target.description})`);
    }

    const match = target.pattern.exec(text);
    if (!match) {
      fail(
        `${target.file} does not contain the expected pattern for its version (${target.description}). Update scripts/set-version.mjs.`,
      );
    }

    const next = target.render(version);
    const current = match[2];
    if (current === next) {
      console.log(`  ${target.file}: ${current} (already correct)`);
      continue;
    }

    stale.push(`${target.file}: ${current} -> ${next}`);
    if (options.check) continue;

    const updated = text.replace(target.pattern, `$1${next}$3`);
    await writeFile(file, updated, "utf8");
    console.log(`  ${target.file}: ${current} -> ${next}`);
  }

  await warnAboutTemplates(options.root);

  if (options.check) {
    if (stale.length > 0) {
      console.error("\nset-version: files are out of date:\n  " + stale.join("\n  "));
      process.exit(1);
    }
    console.log("set-version: everything already matches " + tag);
    return;
  }

  if (stale.length === 0) {
    console.log(`set-version: nothing to do, already at ${tag}`);
    return;
  }

  console.log(`set-version: stamped ${tag} into ${stale.length} file(s)`);
}

main().catch((error) => fail(error?.stack ?? String(error)));
